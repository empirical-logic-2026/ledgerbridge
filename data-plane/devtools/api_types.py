"""Writes frontend/src/api/types.ts: the API's response types for the dashboard, generated
from the data plane's OpenAPI schema (CLAUDE.md: shared types generated, never hand-written).

    python -m devtools.api_types          (./dev.ps1 diagrams also runs it)

A small translation of the JSON schemas FastAPI produces, no extra tool: objects become
interfaces, `anyOf` unions, `$ref` the named type, arrays `T[]`, maps `Record<string, T>`,
`const` and `enum` string literals. Decimals arrive as strings (exact amounts: parse them
with the frontend's money helpers, never as floats). `tests/test_api_types.py` fails when the
file is stale.
"""

import json
from pathlib import Path
from typing import Any

from api.main import create_app

TARGET = Path(__file__).resolve().parents[2] / "frontend" / "src" / "api" / "types.ts"
HEADER = (
    "// Generated by `python -m devtools.api_types` from the data plane's OpenAPI schema.\n"
    "// Do not edit: change the Pydantic models in data-plane/api, then run it again.\n"
)


def ts_type(schema: dict[str, Any]) -> str:
    """The TypeScript type of one JSON schema."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(s) for s in schema["anyOf"]))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object":
        values = schema.get("additionalProperties")
        if isinstance(values, dict):
            return f"Record<string, {ts_type(values)}>"
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(kind or "", "unknown")  # fmt: skip


def interface(name: str, schema: dict[str, Any]) -> str:
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, spec in schema.get("properties", {}).items():
        optional = "" if prop in required else "?"
        lines.append(f"  {prop}{optional}: {ts_type(spec)}")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    schemas = create_app().openapi()["components"]["schemas"]
    blocks = [interface(name, schemas[name]) for name in sorted(schemas)]
    return HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(TARGET.parents[2])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
