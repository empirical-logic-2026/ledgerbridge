def _tables() -> dict[str, Table]:
    return {t.name: t for t in Base.metadata.sorted_tables}


def _type(column: object) -> str:
    kind = column.type  # type: ignore[attr-defined]
    for cls, label in (
        (Enum, "enum"), (Boolean, "bool"), (BigInteger, "bigint"), (Integer, "int"),
        (Numeric, "decimal"), (DateTime, "datetime"), (Date, "date"), (JSON, "json"),
        (Text, "text"), (String, "varchar"), (LargeBinary, "binary"),
    ):  # fmt: skip
        if isinstance(kind, cls):
            return label
    return "value"


def _unique_columns(table: Table) -> set[str]:
    columns = {c.name for c in table.columns if c.unique}
    for constraint in table.constraints:
        if constraint.__class__.__name__ == "UniqueConstraint":
            columns.update(c.name for c in constraint.columns)  # type: ignore[attr-defined]
    return columns


def _entity(table: Table, keys_only: bool) -> list[str]:
    unique = _unique_columns(table)
    lines = [f"    {table.name} {{"]
    for column in table.columns:
        marks = []
        if column.primary_key:
            marks.append("PK")
        if column.foreign_keys:
            marks.append("FK")
        if column.name in unique and not column.primary_key:
            marks.append("UK")
        if not marks and (keys_only or column.name not in DESCRIPTIVE):
            continue
        comment = ""
        if column.foreign_keys:
            target = next(iter(column.foreign_keys)).column.table.name
            comment = f' "to {target}"'
        lines.append(f"        {_type(column)} {column.name} {', '.join(marks)}{comment}".rstrip())
    lines.append("    }")
    return lines


def _stub(table: Table) -> list[str]:
    keys = [c for c in table.columns if c.primary_key]
    body = [f"        {_type(c)} {c.name} PK" for c in keys]
    return [f"    {table.name} {{", *body, "    }"]


def er_diagram(area: Area) -> str:
    tables = _tables()
    shown = [tables[name] for name in area.tables]
    context = [tables[name] for name in area.context]
    names = {t.name for t in shown} | {t.name for t in context}
    lines = ["---", f'title: "{area.title}"', "---", HEADER, "erDiagram"]
    for table in shown:
        lines += _entity(table, area.overview)
    for table in context:
        lines += _stub(table)
    for table in shown:
        for column in table.columns:
            for fk in column.foreign_keys:
                target = fk.column.table.name
                if target not in names:
                    continue
                tracking = table.schema == ACCOUNTING and table.name != "entity_sources"
                if area.overview and tracking and column.name in TRACKING:
                    continue
                parent = "|o" if column.nullable else "||"
                lines.append(f'    {target} {parent}--o{{ {table.name} : "{column.name}"')
    return "\n".join(lines) + "\n"


def schema_diagram() -> str:
    tables = _tables()
    grouped = {name for _, _, names in SCHEMA_GROUPS for name in names}
    missing = sorted(set(tables) - grouped)
    if missing:
        raise ValueError(f"tables not in a schema diagram group: {', '.join(missing)}")
    lines = [
        "---",
        'title: "The four databases and the database users"',
        "---",
        HEADER,
        "flowchart LR",
    ]
    for key, label, _, _ in USERS:
        lines.append(f'    {key}(["{label}"])')
    lines += ['    subgraph mysql["MySQL server: four databases"]', "    direction TB"]
    for db in ALL_DATABASES:
        lines.append(f'    subgraph {db}["{db}"]')
        groups = [(label, names) for d, label, names in SCHEMA_GROUPS if d == db]
        if not groups:
            lines.append(
                f'        {db}_planned["PLANNED (M6): reporting views and aggregates<br/>'
                'the only database the AI can read"]'
            )
        for number, (label, names) in enumerate(groups, start=1):
            items = "<br/>".join(sorted(names))
            lines.append(f'        {db}_{number}["<b>{label}</b><br/>{items}"]')
        lines.append("    end")
    lines.append("    end")
    for key, _, access, dbs in USERS:
        arrow = "==>" if key == "ai_ro" else "-->"
        targets = ["mysql"] if dbs == ALL_DATABASES else list(dbs)
        for db in targets:
            lines.append(f'    {key} {arrow}|"{access}"| {db}')
    lines.append(
        "    classDef planned fill:#f3f4f6,stroke:#9ca3af,stroke-dasharray:5 5,color:#4b5563"
    )
    if not any(d == REPORTING for d, _, _ in SCHEMA_GROUPS):
        lines.append(f"    class {REPORTING}_planned planned")
    return "\n".join(lines) + "\n"


def generated() -> dict[str, str]:
    """File name -> content of every generated diagram source."""
    covered = {name for area in AREAS[:-1] for name in area.tables}
    missing = sorted(set(_tables()) - covered)
    if missing:
        raise ValueError(f"tables not assigned to a diagram area: {', '.join(missing)}")
    out = {f"{area.file}.mmd": er_diagram(area) for area in AREAS}
    out["schema-databases.mmd"] = schema_diagram()
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m devtools.diagrams")
    parser.add_argument("--check", action="store_true", help="exit 1 if out of date")
    args = parser.parse_args(argv)
    stale = []
    for name, content in generated().items():
        path = OUT / name
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current == content:
            continue
        stale.append(name)
        if not args.check:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if args.check:
        if stale:
            print(f"Out of date: {', '.join(stale)}. Run ./dev.ps1 diagrams.", file=sys.stderr)
            return 1
        print("Generated diagram sources are up to date.")
        return 0
    print(
        f"Wrote {len(stale)} generated diagram sources" + (f": {', '.join(stale)}" if stale else "")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
